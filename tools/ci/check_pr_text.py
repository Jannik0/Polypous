#!/usr/bin/env python3
"""Attribution check for a pull request's title and description.

Enforces the attribution rules from CLAUDE.md ("Conventions") and docs/development-workflow.md §5.
The PR title and description become the squash commit message on `main`, so they must not contain:

- a Claude Code session link (`claude.ai/code`) or a `Claude-Session` trailer,
- a model name (`Opus`, `Sonnet`, `Haiku` or `Fable` followed by a version number).

Agent-authored PRs (the description mentions "Claude Code") must also end with exactly the fixed
footer in `FOOTER`. Human PRs without "Claude Code" in the description skip that check.

Input: the environment variables `PR_TITLE` and `PR_BODY` (the workflow sets them from
`github.event.pull_request`, so the text never passes through shell interpolation).

Exit status: 0 if the text is clean, 1 on a violation. Standard library only.
"""

from __future__ import annotations

import os
import re
import sys

# Forbidden patterns, in one place. Cloud harnesses append a session link to PR descriptions (for
# example `_Generated by [Claude Code](https://claude.ai/code/session_…)_`) and some add a model
# name or a `Claude-Session:` trailer, even though `.claude/settings.json` and CLAUDE.md say not
# to. Squash merges copy the description into the commit on `main`, where it cannot be removed.
# Matching is case-insensitive.
FORBIDDEN: list[tuple[str, re.Pattern[str]]] = [
    ("Claude Code session link", re.compile(r"claude\.ai/code", re.IGNORECASE)),
    ("Claude-Session trailer", re.compile(r"claude-session", re.IGNORECASE)),
    # A model family name followed by a version: "Opus 5.5", "sonnet-4", "claude-haiku-5-5", "Fable v5".
    (
        "model name",
        re.compile(r"\b(opus|sonnet|haiku|fable)[\s_-]*v?\d+([.-]\d+)*", re.IGNORECASE),
    ),
]

# The exact last line of an agent-authored PR description (CLAUDE.md "Conventions").
FOOTER = "🤖 Generated with [Claude Code](https://claude.com/claude-code)"

# Its presence marks a description as agent-authored.
AGENT_MARKER = "Claude Code"


def check(title: str, body: str) -> list[str]:
    """Return one error message per violation; empty if title and body are clean."""
    errors = []
    body = body.replace("\r\n", "\n")
    for where, text in (("title", title), ("description", body)):
        for what, pattern in FORBIDDEN:
            for m in pattern.finditer(text):
                errors.append(f"PR {where} contains a {what}: {m.group(0)!r}")
    if AGENT_MARKER in body and not body.rstrip().endswith("\n" + FOOTER) and body.strip() != FOOTER:
        errors.append(f"agent-authored PR description must end with exactly: {FOOTER}")
    return errors


def main() -> int:
    errors = check(os.environ.get("PR_TITLE", ""), os.environ.get("PR_BODY", ""))
    for e in errors:
        print(f"::error::{e}")
    if errors:
        print(
            "\nEdit the PR title/description to fix this; the check re-runs on edit. "
            "Attribution names Claude, never the model, and never links a session "
            "(CLAUDE.md, docs/development-workflow.md §5).",
            file=sys.stderr,
        )
        return 1
    print("PR title and description are clean.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
