#!/usr/bin/env python3
"""Tests for check_pr_text.py.

Run with: python3 -m unittest discover -s tools/ci -p 'test_*.py' -v
"""

from __future__ import annotations

import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import check_pr_text as cpt  # noqa: E402

TITLE = "backend: add DynTensor"
FOOTER = cpt.FOOTER


class CheckPrText(unittest.TestCase):
    def test_clean_agent_pr(self) -> None:
        body = f"## Summary\n\nAdds a thing. Uses Claude Code.\n\n{FOOTER}\n"
        self.assertEqual(cpt.check(TITLE, body), [])

    def test_clean_agent_pr_crlf(self) -> None:
        body = f"## Summary\r\n\r\nAdds a thing.\r\n\r\n{FOOTER}"
        self.assertEqual(cpt.check(TITLE, body), [])

    def test_session_link(self) -> None:
        body = f"Adds a thing.\n\n{FOOTER}\n\n_Generated by [Claude Code](https://claude.ai/code/session_X)_"
        errors = cpt.check(TITLE, body)
        self.assertTrue(any("session link" in e for e in errors), errors)
        # The footer is no longer the last line either.
        self.assertTrue(any("must end with" in e for e in errors), errors)

    def test_session_trailer(self) -> None:
        body = f"Adds a thing.\n\nClaude-Session: abc123\n\n{FOOTER}"
        self.assertTrue(any("Claude-Session" in e for e in cpt.check(TITLE, body)))

    def test_model_names(self) -> None:
        for text in ("Opus 5.5", "written by sonnet 4", "claude-haiku-5-5", "FABLE-5.1", "Opus v5"):
            with self.subTest(text=text):
                errors = cpt.check(TITLE, f"{text}\n\n{FOOTER}")
                self.assertTrue(any("model name" in e for e in errors), errors)

    def test_model_name_in_title(self) -> None:
        errors = cpt.check("docs: notes from Opus 5.5", f"Body.\n\n{FOOTER}")
        self.assertTrue(any(e.startswith("PR title") for e in errors), errors)

    def test_family_word_without_version_is_fine(self) -> None:
        body = f"The magnum opus of tensor code; a haiku about sonnets.\n\n{FOOTER}"
        self.assertEqual(cpt.check(TITLE, body), [])

    def test_human_pr_without_footer(self) -> None:
        self.assertEqual(cpt.check(TITLE, "Fixes a typo in the README."), [])
        self.assertEqual(cpt.check(TITLE, ""), [])

    def test_agent_pr_missing_footer(self) -> None:
        errors = cpt.check(TITLE, "Made with Claude Code.")
        self.assertEqual(len(errors), 1)
        self.assertIn("must end with", errors[0])

    def test_agent_pr_altered_footer(self) -> None:
        body = "Adds a thing.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code) by an agent"
        self.assertTrue(any("must end with" in e for e in cpt.check(TITLE, body)))


if __name__ == "__main__":
    unittest.main()
